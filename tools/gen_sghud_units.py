"""Generate client/sgrender/sghud_units.h: unit base name (English / zh-CN / zh-TW, as the client shows it) ->
branch (0 INF, 1 MOB, 2 AVI, 3 ORG) for the battlefield HUD (squad cards, selected unit).
Sources: server/units_manual.json (official manual: category of every chassis) + server/unitnames.py (CN / TW names).
Run from the repository root:  python3 tools/gen_sghud_units.py   (test101 checks the header is up to date)."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORGANIC = ["Oizys", "Ubik", "Manta", "Slanth", "Mamos", "Poda", "Larva", "Quorg"]   # Factory tab 3 (units_items_lab.UNITS)
REMOVED = {"SatCom"}


def build():
    sys.path.insert(0, os.path.join(ROOT, "server"))
    import unitnames as U
    d = json.load(open(os.path.join(ROOT, "server", "units_manual.json"), encoding="utf-8"))
    cat = {"Infantry": 0, "Mobile": 1, "Aviation": 2}
    br = {}
    for r in d["units"]:
        t = cat.get((r.get("fields") or {}).get("category"))
        if t is None:
            continue
        br.setdefault(re.sub(r"-Mk\d+$", "", r["name"]), t)
    for n in ORGANIC:
        br[n] = 3
    for n in REMOVED:
        br.pop(n, None)
    rows = []
    for en, t in sorted(br.items()):
        for n in sorted({en, U.CN.get(en, en), U.TW.get(en, en)}):
            rows.append((n, t, en))
    out = ["/* generated by tools/gen_sghud_units.py from server/units_manual.json + unitnames.py: unit base name",
           "   (EN / zh-CN / zh-TW) -> branch (0 INF, 1 MOB, 2 AVI, 3 ORG) and the English base name.  Do not edit. */",
           "static const struct { const wchar_t *name; int branch; const wchar_t *en; } HUD_UNITS[] = {"]
    out += ['    {L"%s", %d, L"%s"},' % (n, t, en) for n, t, en in rows]
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = os.path.join(ROOT, "client", "sgrender", "sghud_units.h")
    text = build()
    if "--check" in sys.argv:
        ok = os.path.exists(path) and open(path, encoding="utf-8").read() == text
        print("sghud_units.h up to date" if ok else "sghud_units.h OUT OF DATE")
        sys.exit(0 if ok else 1)
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", path, text.count("\n") - 4, "names")
